"""Assemble the single-file submission main.py.

main.py = embedded feature modules (sbrt/features, augment, evidence, volstate, disttest, bocpd, nbm; each executed in its own
namespace because they share constant names) + the column lists the models were tuned with (baked in here from the
cv_out importance files) + submission_template.py.

Run:  python make_submission.py
Re-run it whenever a module in sbrt/ or submission_template.py changes. Never edit main.py by hand.
The platform only receives main.py, so it must not import anything from sbrt/ (checked below).
"""
import hashlib
import os
import re
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)

MODULES = [("F", "features", {}), ("AUG", "augment", {}), ("EV", "evidence", {"F"}), ("VS", "volstate", {"F"}),
           ("DT", "disttest", {"F", "VS"}), ("BO", "bocpd", {"EV", "F", "VS"}),
           ("NBM", "nbm", {"BO", "EV", "F", "VS"})]
# research-only code removed from a module before embedding: top-level functions (gate training / self-tests that
# read sbrt.data or files next to the package) and module-level lines that use __file__ (undefined inside exec)
DROP_DEFS = {"nbm": ("train", "load_model", "check", "selftest")}
DROP_LINES = {"nbm": r"^WEIGHTS = .*\n"}   # file path built from the (removed) DATA line
GRU_IMP = os.path.join(here, "cv_out", "importance_loc.csv")          # ranking used by gru_cv.py --feat-top
GRU_TOP_K, GRU_TOP_HASH = 20, "b740fa"                                  # the cached GRU inputs' hash
SVM_IMP = os.path.join(here, "cv_out", "importance_aug2_df_bo_nbm_bs24_ep25.csv")   # the cv.py svm_nbm run
SVM_TOP = 100
SVM_HEAD = ["ctx_logn", "ctx_skew", "ctx_kurt", "ctx_rho1", "ctx_phi", "t_log", "nb_lvr", "vol_persist",
            "vol_lvh1000", "vol_lvh200", "win10_tail3", "nb_logodds"]   # first 12 as printed in cv_out/summary_svm_nbm.txt


def module_source(name):
    src = open(os.path.join(here, "sbrt", f"{name}.py"), encoding="utf-8").read()
    cut = src.find("\ndef _selftest")
    if cut >= 0:
        src = src[:cut] + "\n"
    cut = src.find("\nif __name__ ==")
    if cut >= 0:
        src = src[:cut] + "\n"
    for fn in DROP_DEFS.get(name, ()):   # a top-level def runs until the next top-level statement
        src, k = re.subn(rf"^def {fn}\(.*?(?=^\S|\Z)", "", src, count=1, flags=re.M | re.S)
        if k != 1:
            sys.exit(f"sbrt/{name}.py: function {fn} not found")
    src = re.sub(r"^.*__file__.*\n", "", src, flags=re.M)
    if name in DROP_LINES:
        src = re.sub(DROP_LINES[name], "", src, flags=re.M)
    src = src.replace("@njit(cache=True, nogil=True)", "@njit(nogil=True)").replace("@njit(cache=True)", "@njit")
    src = re.sub(r"^from sbrt import \w+ as \w+[ \t]*(#.*)?\n", "", src, flags=re.M)
    if "cache=True" in src or re.search(r"^\s*(from|import)\s+sbrt", src, re.M):
        sys.exit(f"sbrt/{name}.py: leftover cache=True or sbrt import after stripping")
    return src


def ranked(path):
    if not os.path.exists(path):
        sys.exit(f"missing {path} (needed to bake the model's column lists)")
    with open(path, encoding="utf-8") as fh:
        next(fh)
        return [line.split(",")[0] for line in fh]


def baked_lists():
    from sbrt import features as F, evidence as EV, volstate as VS, disttest as DT, bocpd as BO, nbm as NB
    tree_names = (list(F.FEATURE_NAMES) + list(EV.FEATURE_NAMES[:EV.N_COMPACT]) + list(VS.FEATURE_NAMES)
                  + [n for n in DT.FEATURE_NAMES if not n.startswith("dist_z_")]
                  + list(BO.FEATURE_NAMES) + list(NB.FEATURE_NAMES))      # cv.py order with --bocpd --nbm
    gru = [n for n in ranked(GRU_IMP) if n in F.FEATURE_NAMES and not n.startswith(("ctx_", "t_log", "z_now"))][:GRU_TOP_K]
    h = hashlib.md5(",".join(gru).encode()).hexdigest()[:6]
    if h != GRU_TOP_HASH:
        sys.exit(f"GRU top-{GRU_TOP_K} list hash {h} != {GRU_TOP_HASH} used by the cross-validated GRU")
    svm = [n for n in tree_names if n == "t_log" or n.startswith("ctx_")]          # cv.py svm_columns()
    for n in ranked(SVM_IMP):
        if len(svm) >= SVM_TOP + 6:
            break
        if n in tree_names and n not in svm:
            svm.append(n)
    if len(svm) != SVM_TOP + 6 or svm[:len(SVM_HEAD)] != SVM_HEAD:
        sys.exit(f"SVM column list does not match the cross-validated svm_nbm run: {svm[:12]}")
    return gru, svm, len(tree_names)


def main():
    gru, svm, n_tree = baked_lists()
    parts = ['"""AUTO-GENERATED by make_submission.py from sbrt/ and submission_template.py. Do not edit by hand."""\n'
             "import sys as _sys\nimport types as _types\n\n\n"
             "def _embed(name, src, deps):\n"
             "    m = _types.ModuleType(name)\n"
             "    m.__dict__.update(deps)\n"
             "    _sys.modules[name] = m\n"
             "    exec(compile(src, name, 'exec'), m.__dict__)\n"
             "    return m\n\n\n"]
    for alias, name, deps in MODULES:
        dep = "{" + ", ".join(f"'{d}': {d}" for d in sorted(deps)) + "}"
        parts.append(f"_SRC_{alias} = {module_source(name)!r}\n{alias} = _embed('sbrt_{name}', _SRC_{alias}, {dep})\n\n")
    parts.append(f"GRU_TOP_NAMES = {gru!r}\nSVM_NAMES = {svm!r}\n")
    parts.append(open(os.path.join(here, "submission_template.py"), encoding="utf-8").read())
    code = "".join(parts)
    if re.search(r"^\s*(from|import)\s+sbrt", code, re.M):
        sys.exit("main.py would import from sbrt -> the cloud would not find it")
    out = os.path.join(here, "main.py")
    open(out, "w", encoding="utf-8").write(code)
    print(f"wrote main.py ({len(code):,} chars): {n_tree} tree columns, GRU top-{len(gru)}, SVM {len(svm)} tree columns "
          f"+ the NBM hidden-state channels (HANDOFF 27)")
    # main.py must import on its own, with no sbrt/ package anywhere on the path
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, "main.py"), "w", encoding="utf-8").write(code)
        r = subprocess.run([sys.executable, "-c", "import main; print(main.N_TREE, main.GRU_CIN, len(main.SVM_COLS))"],
                           cwd=d, capture_output=True, text=True, env=dict(os.environ, PYTHONPATH=""))
        if r.returncode != 0:
            sys.exit("main.py does not import standalone:\n" + r.stderr[-3000:])
        print("standalone import OK:", r.stdout.strip())


if __name__ == "__main__":
    main()
